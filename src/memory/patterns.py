def mark_pattern_normal(
    store: MemoryStore,
    memory_id: str,
    *,
    verification_source: str,
) -> PatternMemory:
    """
    Explicitly record one verified-normal
    observation.

    This must be called only when an authoritative
    workflow/operator has classified the pattern
    as normal.
    """

    memory = store.require(
        memory_id
    )

    if not isinstance(
        memory,
        PatternMemory,
    ):
        raise TypeError(
            "memory_id does not reference "
            "PatternMemory"
        )

    memory.verified_normal_count += 1

    memory.verification_status = (
        VerificationStatus.
        VERIFIED.value
    )

    memory.attributes[
        "last_verification_source"
    ] = verification_source

    memory.attributes[
        "last_verified_classification"
    ] = "normal"

    memory.touch()

    stored = store.put(
        memory
    )

    if not isinstance(
        stored,
        PatternMemory,
    ):
        raise TypeError(
            "Memory store returned a "
            "non-PatternMemory object"
        )

    return stored


def mark_pattern_incident(
    store: MemoryStore,
    memory_id: str,
    *,
    incident_id: str,
    verification_source: str,
) -> PatternMemory:
    """
    Explicitly record one verified
    incident-associated occurrence.
    """

    memory = store.require(
        memory_id
    )

    if not isinstance(
        memory,
        PatternMemory,
    ):
        raise TypeError(
            "memory_id does not reference "
            "PatternMemory"
        )

    memory.verified_incident_count += 1

    memory.incident_ids = sorted(
        set(
            memory.incident_ids
        )
        | {
            incident_id
        }
    )

    memory.verification_status = (
        VerificationStatus.
        VERIFIED.value
    )

    memory.attributes[
        "last_verification_source"
    ] = verification_source

    memory.attributes[
        "last_verified_classification"
    ] = "incident"

    memory.touch()

    stored = store.put(
        memory
    )

    if not isinstance(
        stored,
        PatternMemory,
    ):
        raise TypeError(
            "Memory store returned a "
            "non-PatternMemory object"
        )

    return stored


def reject_pattern_classification(
    store: MemoryStore,
    memory_id: str,
    *,
    verification_source: str,
) -> PatternMemory:
    """
    Record that an existing classification or
    hypothesis was rejected.

    Historical occurrence information remains
    intact.
    """

    memory = store.require(
        memory_id
    )

    if not isinstance(
        memory,
        PatternMemory,
    ):
        raise TypeError(
            "memory_id does not reference "
            "PatternMemory"
        )

    memory.verification_status = (
        VerificationStatus.
        REJECTED.value
    )

    memory.attributes[
        "last_verification_source"
    ] = verification_source

    memory.touch()

    stored = store.put(
        memory
    )

    if not isinstance(
        stored,
        PatternMemory,
    ):
        raise TypeError(
            "Memory store returned a "
            "non-PatternMemory object"
        )

    return stored


