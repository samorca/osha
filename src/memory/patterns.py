def list_pattern_memory(
    store: MemoryStore,
    *,
    environment_id: Optional[
        str
    ] = None,
    resource_id: Optional[
        str
    ] = None,
    verified_only: bool = False,
    active_only: bool = False,
    limit: Optional[int] = None,
) -> List[
    PatternMemory
]:
    query = MemoryQuery(
        memory_types=(
            "pattern",
        ),
        environment_ids=(
            (
                environment_id,
            )
            if environment_id
            else ()
        ),
        resource_ids=(
            (
                resource_id,
            )
            if resource_id
            else ()
        ),
        verification_statuses=(
            (
                VerificationStatus.
                VERIFIED.value,
            )
            if verified_only
            else ()
        ),
        active_only=active_only,
        limit=limit,
    )

    return [
        memory
        for memory
        in store.query(query)
        if isinstance(
            memory,
            PatternMemory,
        )
    ]


def pattern_history(
    store: MemoryStore,
    fingerprint: str,
    *,
    environment_id: str,
    pattern_type: Optional[
        str
    ] = None,
) -> Optional[
    PatternMemory
]:
    return find_pattern_memory(
        store,
        environment_id=(
            environment_id
        ),
        fingerprint=fingerprint,
        pattern_type=(
            pattern_type
        ),
    )


def pattern_incident_rate(
    memory: PatternMemory,
) -> Optional[float]:
    """
    Ratio of verified classifications that were
    incident-associated.

    This deliberately ignores unverified
    occurrences.

    None means there is no verified classification
    history yet.
    """

    verified_total = (
        memory.
        verified_incident_count
        + memory.
        verified_normal_count
    )

    if verified_total <= 0:
        return None

    return (
        memory.
        verified_incident_count
        / verified_total
    )


def pattern_normal_rate(
    memory: PatternMemory,
) -> Optional[float]:
    verified_total = (
        memory.
        verified_incident_count
        + memory.
        verified_normal_count
    )

    if verified_total <= 0:
        return None

    return (
        memory.
        verified_normal_count
        / verified_total
    )


def pattern_history_summary(
    memories: Iterable[
        PatternMemory
    ],
) -> Dict[str, Any]:
    """
    Summarize persistent pattern history.
    """

    memory_list = list(
        memories
    )

    verified = [
        memory
        for memory in memory_list
        if (
            memory.verification_status
            == VerificationStatus.
            VERIFIED.value
        )
    ]

    verified_incident_occurrences = sum(
        memory.
        verified_incident_count
        for memory
        in memory_list
    )

    verified_normal_occurrences = sum(
        memory.
        verified_normal_count
        for memory
        in memory_list
    )

    return {
        "pattern_memory_count": (
            len(memory_list)
        ),
        "verified_pattern_count": (
            len(verified)
        ),
        "total_observed_occurrences": sum(
            memory.occurrence_count
            for memory
            in memory_list
        ),
        "verified_incident_occurrences": (
            verified_incident_occurrences
        ),
        "verified_normal_occurrences": (
            verified_normal_occurrences
        ),
        "patterns_with_incident_history": (
            sum(
                1
                for memory
                in memory_list
                if (
                    memory.
                    verified_incident_count
                    > 0
                )
            )
        ),
        "patterns_with_normal_history": (
            sum(
                1
                for memory
                in memory_list
                if (
                    memory.
                    verified_normal_count
                    > 0
                )
            )
        ),
    }


class PatternMemoryManager:
    """
    Convenience interface for memory.pipeline and
    future intelligence-history integration.
    """

    def __init__(
        self,
        store: MemoryStore,
    ) -> None:
        self.store = store

    def remember(
        self,
        pattern: Pattern,
        *,
        incident_ids: Iterable[
            str
        ] = (),
    ) -> PatternMemory:
        return remember_pattern(
            self.store,
            pattern,
            incident_ids=(
                incident_ids
            ),
        )

    def remember_many(
        self,
        patterns: Iterable[
            Pattern
        ],
        *,
        incident_ids_by_pattern: Optional[
            Dict[str, List[str]]
        ] = None,
    ) -> List[
        PatternMemory
    ]:
        return remember_patterns(
            self.store,
            patterns,
            incident_ids_by_pattern=(
                incident_ids_by_pattern
            ),
        )

    def history(
        self,
        fingerprint: str,
        *,
        environment_id: str,
        pattern_type: Optional[
            str
        ] = None,
    ) -> Optional[
        PatternMemory
    ]:
        return pattern_history(
            self.store,
            fingerprint,
            environment_id=(
                environment_id
            ),
            pattern_type=(
                pattern_type
            ),
        )

    def verify_normal(
        self,
        memory_id: str,
        *,
        verification_source: str,
    ) -> PatternMemory:
        return mark_pattern_normal(
            self.store,
            memory_id,
            verification_source=(
                verification_source
            ),
        )

    def verify_incident(
        self,
        memory_id: str,
        *,
        incident_id: str,
        verification_source: str,
    ) -> PatternMemory:
        return mark_pattern_incident(
            self.store,
            memory_id,
            incident_id=incident_id,
            verification_source=(
                verification_source
            ),
        )
