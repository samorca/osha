def unique_strings(
    values: Iterable[
        Optional[str]
    ],
) -> List[str]:
    return sorted(
        {
            value
            for value in values
            if value
        }
    )


def pattern_memory_from_pattern(
    pattern: Pattern,
    *,
    incident_ids: Iterable[
        str
    ] = (),
    verification_status: str = (
        VerificationStatus.
        UNVERIFIED.value
    ),
) -> PatternMemory:
    """
    Convert one intelligence Pattern into
    long-term PatternMemory.

    Observing the pattern does not automatically
    classify it as normal or incident-causing.
    """

    pattern.finalize()

    source_ids = []

    if pattern.pattern_id:
        source_ids.append(
            pattern.pattern_id
        )

    memory = PatternMemory(
        environment_id=(
            pattern.environment_id
        ),
        pattern_id=(
            pattern.pattern_id
        ),
        fingerprint=(
            pattern.fingerprint
        ),
        pattern_type=(
            pattern.pattern_type
        ),
        name=pattern.name,
        occurrence_count=(
            pattern.occurrence_count
        ),
        first_seen=(
            pattern.first_seen
        ),
        last_seen=(
            pattern.last_seen
        ),
        providers=list(
            pattern.providers
        ),
        signal_types=list(
            pattern.signal_types
        ),
        incident_ids=(
            unique_strings(
                incident_ids
            )
        ),
        latest_novelty_score=(
            pattern.novelty_score
        ),
        resource_ids=list(
            pattern.resource_ids
        ),
        source_ids=source_ids,
        verification_status=(
            verification_status
        ),
        tags=[
            "operational_pattern"
        ],
        attributes={
            "latest_record_ids": list(
                pattern.record_ids
            ),
            "latest_pattern_attributes": (
                dict(
                    pattern.attributes
                )
            ),
        },
    )

    return memory.finalize()


def find_pattern_memory(
    store: MemoryStore,
    *,
    environment_id: str,
    fingerprint: str,
    pattern_type: Optional[
        str
    ] = None,
) -> Optional[
    PatternMemory
]:
    """
    Find persistent history for one fingerprint.

    Fingerprint and environment form the primary
    pattern-history identity.
    """

    query = MemoryQuery(
        memory_types=(
            "pattern",
        ),
        environment_ids=(
            environment_id,
        ),
        newest_first=True,
    )

    for memory in store.query(
        query
    ):
        if not isinstance(
            memory,
            PatternMemory,
        ):
            continue

        if (
            memory.fingerprint
            != fingerprint
        ):
            continue

        if (
            pattern_type is not None
            and memory.pattern_type
            != pattern_type
        ):
            continue

        return memory

    return None


def earliest_timestamp(
    left: Optional[str],
    right: Optional[str],
) -> Optional[str]:
    if left is None:
        return right

    if right is None:
        return left

    # All upstream timestamps should already be
    # normalized ISO-8601 values. Lexical
    # comparison is therefore sufficient for
    # canonical UTC timestamps generated by the
    # pipeline.
    return min(
        left,
        right,
    )


def latest_timestamp(
    left: Optional[str],
    right: Optional[str],
) -> Optional[str]:
    if left is None:
        return right

    if right is None:
        return left

    return max(
        left,
        right,
    )


def merge_pattern_memory(
    existing: PatternMemory,
    incoming: PatternMemory,
) -> PatternMemory:
    """
    Merge one newly observed pattern batch into
    historical memory.

    `incoming.occurrence_count` describes the
    newly processed observations. We add it to
    historical occurrence count.

    Verification counters are deliberately not
    changed here.
    """

    existing.occurrence_count = (
        max(
            0,
            existing.occurrence_count,
        )
        + max(
            0,
            incoming.occurrence_count,
        )
    )

    existing.first_seen = (
        earliest_timestamp(
            existing.first_seen,
            incoming.first_seen,
        )
    )

    existing.last_seen = (
        latest_timestamp(
            existing.last_seen,
            incoming.last_seen,
        )
    )

    existing.providers = sorted(
        set(
            existing.providers
        )
        | set(
            incoming.providers
        )
    )

    existing.signal_types = sorted(
        set(
            existing.signal_types
        )
        | set(
            incoming.signal_types
        )
    )

    existing.resource_ids = sorted(
        set(
            existing.resource_ids
        )
        | set(
            incoming.resource_ids
        )
    )

    existing.source_ids = sorted(
        set(
            existing.source_ids
        )
        | set(
            incoming.source_ids
        )
    )

    existing.incident_ids = sorted(
        set(
            existing.incident_ids
        )
        | set(
            incoming.incident_ids
        )
    )

    existing.tags = sorted(
        set(
            existing.tags
        )
        | set(
            incoming.tags
        )
    )

    existing.latest_novelty_score = (
        incoming.latest_novelty_score
    )

    if incoming.name:
        existing.name = (
            incoming.name
        )

    if incoming.pattern_id:
        existing.pattern_id = (
            incoming.pattern_id
        )

    existing.attributes.update(
        incoming.attributes
    )

    existing.touch()

    return existing.finalize()


def remember_pattern(
    store: MemoryStore,
    pattern: Pattern,
    *,
    incident_ids: Iterable[
        str
    ] = (),
) -> PatternMemory:
    """
    Create or update long-term history for one
    pattern.
    """

    incoming = (
        pattern_memory_from_pattern(
            pattern,
            incident_ids=(
                incident_ids
            ),
        )
    )

    existing = find_pattern_memory(
        store,
        environment_id=(
            incoming.environment_id
        ),
        fingerprint=(
            incoming.fingerprint
        ),
        pattern_type=(
            incoming.pattern_type
        ),
    )

    if existing is not None:
        incoming = (
            merge_pattern_memory(
                existing,
                incoming,
            )
        )

    stored = store.put(
        incoming
    )

    if not isinstance(
        stored,
        PatternMemory,
    ):
        raise TypeError(
            "Memory store returned a "
            "non-PatternMemory object"
        )

    return stored


def remember_patterns(
    store: MemoryStore,
    patterns: Iterable[
        Pattern
    ],
    *,
    incident_ids_by_pattern: Optional[
        Dict[str, List[str]]
    ] = None,
) -> List[
    PatternMemory
]:
    """
    Persist an intelligence pattern batch.
    """

    incident_map = (
        incident_ids_by_pattern
        or {}
    )

    output = []

    for pattern in patterns:
        pattern.finalize()

        incidents = (
            incident_map.get(
                pattern.pattern_id
                or "",
                [],
            )
        )

        output.append(
            remember_pattern(
                store,
                pattern,
                incident_ids=incidents,
            )
        )

    return output


