"""
OSHA Prediction Persistence Model.

Stores predictions produced by OSHA's intelligence and forecasting systems.

A prediction represents a model-generated assessment about a resource or
infrastructure condition.

Examples:

    - CPU capacity exhaustion forecast
    - memory exhaustion forecast
    - disk capacity forecast
    - network saturation forecast
    - infrastructure failure probability
    - anomaly risk
    - service degradation prediction
    - resource health forecast

The model preserves:
    - resource identity
    - model identity and version
    - prediction horizon
    - confidence
    - observed/current values
    - predicted values
    - thresholds
    - evidence references
    - lifecycle and verification state

Predictions should be treated as model output with provenance, not as
unqualified facts.
"""

from __future__ import annotations

import enum
import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    JSON,
    String,
    Text,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from ..base import Base, TenantMixin, VersionMixin


# ---------------------------------------------------------------------------
# Prediction classification
# ---------------------------------------------------------------------------

class PredictionType(str, enum.Enum):
    """Canonical OSHA prediction families."""

    CAPACITY = "capacity"
    EXHAUSTION = "exhaustion"

    CPU = "cpu"
    MEMORY = "memory"
    DISK = "disk"
    NETWORK = "network"

    FAILURE = "failure"
    DEGRADATION = "degradation"
    AVAILABILITY = "availability"

    ANOMALY_RISK = "anomaly_risk"
    INCIDENT_RISK = "incident_risk"

    RESOURCE_HEALTH = "resource_health"
    WORKLOAD = "workload"

    CUSTOM = "custom"


class PredictionStatus(str, enum.Enum):
    """Lifecycle of a prediction."""

    PENDING = "pending"
    ACTIVE = "active"
    EXPIRED = "expired"
    VERIFIED = "verified"
    INVALIDATED = "invalidated"
    SUPERSEDED = "superseded"


class PredictionOutcome(str, enum.Enum):
    """Outcome determined after a prediction can be evaluated."""

    UNKNOWN = "unknown"

    TRUE_POSITIVE = "true_positive"
    TRUE_NEGATIVE = "true_negative"

    FALSE_POSITIVE = "false_positive"
    FALSE_NEGATIVE = "false_negative"

    PARTIALLY_CORRECT = "partially_correct"
    NOT_EVALUATED = "not_evaluated"


class PredictionSeverity(str, enum.Enum):
    """Operational severity associated with a prediction."""

    INFO = "info"
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


# ---------------------------------------------------------------------------
# Prediction model
# ---------------------------------------------------------------------------

class Prediction(
    TenantMixin,
    VersionMixin,
    Base,
):
    """
    Persisted prediction generated by OSHA.

    A prediction is attached to a Resource whenever the prediction concerns a
    particular infrastructure object.

    Resource examples:

        Linux host
        Kubernetes node
        pod
        container
        OpenStack instance
        Ceph OSD
        disk
        network interface

    Predictions retain model identity and evidence so later systems can
    understand which model produced an assessment and evaluate its outcome.
    """

    __tablename__ = "predictions"

    __table_args__ = (
        CheckConstraint(
            "confidence IS NULL OR "
            "(confidence >= 0.0 AND confidence <= 1.0)",
            name="prediction_confidence_range",
        ),
        CheckConstraint(
            "probability IS NULL OR "
            "(probability >= 0.0 AND probability <= 1.0)",
            name="prediction_probability_range",
        ),
        CheckConstraint(
            "horizon_seconds IS NULL OR horizon_seconds >= 0",
            name="prediction_horizon_non_negative",
        ),
        Index(
            "ix_predictions_resource_created",
            "resource_id",
            "created_at",
        ),
        Index(
            "ix_predictions_tenant_type_status",
            "tenant_id",
            "prediction_type",
            "status",
        ),
        Index(
            "ix_predictions_model",
            "model_name",
            "model_version",
        ),
        Index(
            "ix_predictions_future",
            "predicted_for",
        ),
        Index(
            "ix_predictions_expiry",
            "expires_at",
        ),
        Index(
            "ix_predictions_incident",
            "incident_id",
        ),
    )

    # ------------------------------------------------------------------
    # Target resource
    # ------------------------------------------------------------------

    resource_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey(
            "resources.id",
            ondelete="SET NULL",
        ),
        nullable=True,
        index=True,
    )

    resource: Mapped["Resource | None"] = relationship(
        "Resource",
        foreign_keys=[resource_id],
        lazy="selectin",
    )

    # ------------------------------------------------------------------
    # Optional operational references
    # ------------------------------------------------------------------

    incident_id: Mapped[uuid.UUID | None] = mapped_column(
        nullable=True,
        index=True,
    )

    anomaly_id: Mapped[uuid.UUID | None] = mapped_column(
        nullable=True,
        index=True,
    )

    correlation_id: Mapped[uuid.UUID | None] = mapped_column(
        nullable=True,
        index=True,
    )

    # ------------------------------------------------------------------
    # Prediction identity
    # ------------------------------------------------------------------

    prediction_type: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
        index=True,
    )

    metric_name: Mapped[str | None] = mapped_column(
        String(255),
        nullable=True,
        index=True,
    )

    title: Mapped[str | None] = mapped_column(
        String(512),
        nullable=True,
    )

    description: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    # ------------------------------------------------------------------
    # Model provenance
    # ------------------------------------------------------------------

    model_id: Mapped[uuid.UUID | None] = mapped_column(
        nullable=True,
        index=True,
    )

    model_name: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
        index=True,
    )

    model_version: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
        index=True,
    )

    model_family: Mapped[str | None] = mapped_column(
        String(128),
        nullable=True,
        index=True,
    )

    training_run_id: Mapped[uuid.UUID | None] = mapped_column(
        nullable=True,
        index=True,
    )

    # ------------------------------------------------------------------
    # Prediction values
    # ------------------------------------------------------------------

    current_value: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    predicted_value: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    lower_bound: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    upper_bound: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    threshold_value: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    unit: Mapped[str | None] = mapped_column(
        String(64),
        nullable=True,
    )

    probability: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    confidence: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    # ------------------------------------------------------------------
    # Prediction horizon
    # ------------------------------------------------------------------

    input_window_start: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    input_window_end: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    generated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )

    predicted_for: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        index=True,
    )

    horizon_seconds: Mapped[int | None] = mapped_column(
        Integer,
        nullable=True,
    )

    expires_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        index=True,
    )

    # ------------------------------------------------------------------
    # Operational classification
    # ------------------------------------------------------------------

    severity: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
        default=PredictionSeverity.INFO.value,
        index=True,
    )

    status: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
        default=PredictionStatus.ACTIVE.value,
        index=True,
    )

    actionable: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
        index=True,
    )

    # ------------------------------------------------------------------
    # Explainability and evidence
    # ------------------------------------------------------------------

    evidence: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
        default=dict,
    )

    features: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
        default=dict,
    )

    explanation: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
        default=dict,
    )

    metadata_payload: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
        default=dict,
    )

    # ------------------------------------------------------------------
    # Outcome / model evaluation
    # ------------------------------------------------------------------

    outcome: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
        default=PredictionOutcome.UNKNOWN.value,
        index=True,
    )

    actual_value: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    evaluated_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    evaluation_notes: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    # ------------------------------------------------------------------
    # Typed helpers
    # ------------------------------------------------------------------

    @property
    def kind(self) -> PredictionType | None:
        """Return the typed prediction family when recognised."""
        try:
            return PredictionType(self.prediction_type)
        except ValueError:
            return None

    @property
    def lifecycle(self) -> PredictionStatus | None:
        """Return the typed prediction lifecycle state."""
        try:
            return PredictionStatus(self.status)
        except ValueError:
            return None

    @property
    def outcome_kind(self) -> PredictionOutcome | None:
        """Return the typed prediction outcome."""
        try:
            return PredictionOutcome(self.outcome)
        except ValueError:
            return None

    @property
    def severity_kind(self) -> PredictionSeverity | None:
        """Return the typed severity."""
        try:
            return PredictionSeverity(self.severity)
        except ValueError:
            return None

    # ------------------------------------------------------------------
    # State operations
    # ------------------------------------------------------------------

    def mark_expired(self) -> None:
        """Mark the prediction as expired."""
        self.status = PredictionStatus.EXPIRED.value
        self.actionable = False

    def mark_superseded(self) -> None:
        """
        Mark the prediction as superseded by a newer model assessment.
        """
        self.status = PredictionStatus.SUPERSEDED.value
        self.actionable = False

    def invalidate(
        self,
        *,
        notes: str | None = None,
    ) -> None:
        """Invalidate the prediction."""
        self.status = PredictionStatus.INVALIDATED.value
        self.actionable = False

        if notes is not None:
            self.evaluation_notes = notes

    def verify(
        self,
        *,
        outcome: PredictionOutcome,
        evaluated_at: datetime,
        actual_value: float | None = None,
        notes: str | None = None,
    ) -> None:
        """
        Record the observed outcome of a prediction.

        This information can later support model-performance analysis and
        retraining pipelines.
        """
        self.status = PredictionStatus.VERIFIED.value
        self.outcome = outcome.value
        self.evaluated_at = evaluated_at
        self.actual_value = actual_value
        self.evaluation_notes = notes

    def set_confidence(
        self,
        confidence: float | None,
    ) -> None:
        """Set model confidence after validating its range."""
        if confidence is not None and not 0.0 <= confidence <= 1.0:
            raise ValueError(
                "prediction confidence must be between 0.0 and 1.0"
            )

        self.confidence = confidence

    def set_probability(
        self,
        probability: float | None,
    ) -> None:
        """Set probability after validating its range."""
        if probability is not None and not 0.0 <= probability <= 1.0:
            raise ValueError(
                "prediction probability must be between 0.0 and 1.0"
            )

        self.probability = probability

    # ------------------------------------------------------------------
    # Safe representation
    # ------------------------------------------------------------------

    def prediction_summary(self) -> dict[str, Any]:
        """Return a serialisable prediction summary."""
        return {
            "id": str(self.id),
            "tenant_id": str(self.tenant_id),
            "resource_id": (
                str(self.resource_id)
                if self.resource_id is not None
                else None
            ),
            "prediction_type": self.prediction_type,
            "metric_name": self.metric_name,
            "model_name": self.model_name,
            "model_version": self.model_version,
            "current_value": self.current_value,
            "predicted_value": self.predicted_value,
            "threshold_value": self.threshold_value,
            "unit": self.unit,
            "probability": self.probability,
            "confidence": self.confidence,
            "severity": self.severity,
            "status": self.status,
            "outcome": self.outcome,
            "generated_at": self.generated_at.isoformat(),
            "predicted_for": (
                self.predicted_for.isoformat()
                if self.predicted_for is not None
                else None
            ),
        }


__all__ = [
    "Prediction",
    "PredictionOutcome",
    "PredictionSeverity",
    "PredictionStatus",
    "PredictionType",
]
