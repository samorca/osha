    # ------------------------------------------------------------------
    # Resource validation
    # ------------------------------------------------------------------

    def _require_resource(
        self,
        *,
        tenant_id: uuid.UUID,
        resource_id: uuid.UUID,
    ) -> Resource:
        """Verify that a prediction target belongs to the tenant."""
        statement = (
            select(Resource)
            .where(
                Resource.id == resource_id,
                Resource.tenant_id == tenant_id,
            )
            .limit(1)
        )

        resource = self.session.scalar(statement)

        if resource is None:
            raise ValueError(
                f"resource {resource_id} does not exist "
                "for the specified tenant"
            )

        return resource

    # ------------------------------------------------------------------
    # Prediction persistence
    # ------------------------------------------------------------------

    def create_prediction(
        self,
        *,
        tenant_id: uuid.UUID,
        prediction_type: str,
        model_name: str,
        model_version: str,
        generated_at: datetime,
        resource_id: uuid.UUID | None = None,
        metric_name: str | None = None,
        title: str | None = None,
        description: str | None = None,
        model_id: uuid.UUID | None = None,
        model_family: str | None = None,
        training_run_id: uuid.UUID | None = None,
        current_value: float | None = None,
        predicted_value: float | None = None,
        lower_bound: float | None = None,
        upper_bound: float | None = None,
        threshold_value: float | None = None,
        unit: str | None = None,
        probability: float | None = None,
        confidence: float | None = None,
        input_window_start: datetime | None = None,
        input_window_end: datetime | None = None,
        predicted_for: datetime | None = None,
        horizon_seconds: int | None = None,
        expires_at: datetime | None = None,
        severity: str = PredictionSeverity.INFO.value,
        actionable: bool = False,
        incident_id: uuid.UUID | None = None,
        anomaly_id: uuid.UUID | None = None,
        correlation_id: uuid.UUID | None = None,
        evidence: dict[str, Any] | None = None,
        features: dict[str, Any] | None = None,
        explanation: dict[str, Any] | None = None,
        metadata_payload: dict[str, Any] | None = None,
    ) -> Prediction:
        """
        Persist a model-generated prediction.

        When a resource ID is supplied, ownership is checked before the
        prediction is persisted.

        The Session is flushed but not committed.
        """
        if resource_id is not None:
            self._require_resource(
                tenant_id=tenant_id,
                resource_id=resource_id,
            )

        if probability is not None and not 0.0 <= probability <= 1.0:
            raise ValueError(
                "prediction probability must be between 0.0 and 1.0"
            )

        if confidence is not None and not 0.0 <= confidence <= 1.0:
            raise ValueError(
                "prediction confidence must be between 0.0 and 1.0"
            )

        if horizon_seconds is not None and horizon_seconds < 0:
            raise ValueError(
                "prediction horizon cannot be negative"
            )

        prediction = Prediction(
            tenant_id=tenant_id,
            resource_id=resource_id,
            prediction_type=prediction_type,
            metric_name=metric_name,
            title=title,
            description=description,
            model_id=model_id,
            model_name=model_name,
            model_version=model_version,
            model_family=model_family,
            training_run_id=training_run_id,
            current_value=current_value,
            predicted_value=predicted_value,
            lower_bound=lower_bound,
            upper_bound=upper_bound,
            threshold_value=threshold_value,
            unit=unit,
            probability=probability,
            confidence=confidence,
            input_window_start=input_window_start,
            input_window_end=input_window_end,
            generated_at=generated_at,
            predicted_for=predicted_for,
            horizon_seconds=horizon_seconds,
            expires_at=expires_at,
            severity=severity,
            status=PredictionStatus.ACTIVE.value,
            actionable=actionable,
            incident_id=incident_id,
            anomaly_id=anomaly_id,
            correlation_id=correlation_id,
            evidence=evidence or {},
            features=features or {},
            explanation=explanation or {},
            metadata_payload=metadata_payload or {},
        )

        self.add(
            prediction,
            flush=True,
        )

        return prediction

    # ------------------------------------------------------------------
    # Operational attachment
    # ------------------------------------------------------------------

    def attach_to_incident(
        self,
        *,
        prediction_id: uuid.UUID,
        incident_id: uuid.UUID,
    ) -> Prediction:
        """Associate a prediction with an incident."""
        prediction = self.get_required(
            prediction_id
        )

        prediction.incident_id = incident_id

        self.flush()

        return prediction

