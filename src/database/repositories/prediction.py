"""
OSHA Prediction Repository.

Persistence interface for predictions generated by OSHA's intelligence and
forecasting systems.

Examples:

    - CPU capacity exhaustion
    - memory exhaustion
    - disk exhaustion
    - network saturation
    - resource degradation
    - infrastructure failure risk
    - anomaly risk
    - incident risk

The repository preserves model provenance and later allows actual outcomes
to be recorded so model performance can be evaluated.

Transaction ownership remains with OSHA's session/service layer.
"""

from __future__ import annotations

import uuid
from collections.abc import Sequence
from datetime import datetime
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session, selectinload

from ..models.prediction import (
    Prediction,
    PredictionOutcome,
    PredictionSeverity,
    PredictionStatus,
)
from ..models.resource import Resource
from .base import BaseRepository


class PredictionRepository(BaseRepository[Prediction]):
    """Repository for OSHA predictions and forecasts."""

    model = Prediction

    def __init__(
        self,
        session: Session,
    ) -> None:
        super().__init__(session)

    # ------------------------------------------------------------------
    # Retrieval
    # ------------------------------------------------------------------

    def get_with_resource(
        self,
        *,
        prediction_id: uuid.UUID,
    ) -> Prediction | None:
        """Return a prediction with its target resource loaded."""
        statement = (
            select(Prediction)
            .options(
                selectinload(
                    Prediction.resource
                )
            )
            .where(
                Prediction.id == prediction_id
            )
            .limit(1)
        )

        return self.session.scalar(statement)

    # ------------------------------------------------------------------
    # Resource queries
    # ------------------------------------------------------------------

    def list_for_resource(
        self,
        *,
        tenant_id: uuid.UUID,
        resource_id: uuid.UUID,
        offset: int = 0,
        limit: int = 100,
        active_only: bool = False,
    ) -> Sequence:
        """
        Return predictions associated with a resource.
        """
        self._validate_pagination(
            offset=offset,
            limit=limit,
        )

        statement = select(Prediction).where(
            Prediction.tenant_id == tenant_id,
            Prediction.resource_id == resource_id,
        )

        if active_only:
            statement = statement.where(
                Prediction.status == PredictionStatus.ACTIVE.value
            )

        statement = (
            statement
            .order_by(
                Prediction.generated_at.desc()
            )
            .offset(offset)
            .limit(limit)
        )

        return tuple(
            self.session.scalars(statement).all()
        )

    # ------------------------------------------------------------------
    # Active predictions
    # ------------------------------------------------------------------

    def list_active(
        self,
        *,
        tenant_id: uuid.UUID,
        resource_id: uuid.UUID | None = None,
        prediction_type: str | None = None,
        severity: str | None = None,
        offset: int = 0,
        limit: int = 100,
    ) -> Sequence:
        """Return currently active predictions."""
        self._validate_pagination(
            offset=offset,
            limit=limit,
        )

        statement = select(Prediction).where(
            Prediction.tenant_id == tenant_id,
            Prediction.status == PredictionStatus.ACTIVE.value,
        )

        if resource_id is not None:
            statement = statement.where(
                Prediction.resource_id == resource_id
            )

        if prediction_type is not None:
            statement = statement.where(
                Prediction.prediction_type == prediction_type
            )

        if severity is not None:
            statement = statement.where(
                Prediction.severity == severity
            )

        statement = (
            statement
            .options(
                selectinload(
                    Prediction.resource
                )
            )
            .order_by(
                Prediction.predicted_for.asc(),
                Prediction.generated_at.desc(),
            )
            .offset(offset)
            .limit(limit)
        )

        return tuple(
            self.session.scalars(statement).all()
        )

