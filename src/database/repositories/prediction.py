    # ------------------------------------------------------------------
    # Lifecycle
    # ------------------------------------------------------------------

    def mark_expired(
        self,
        *,
        prediction_id: uuid.UUID,
    ) -> Prediction:
        """Mark a prediction expired."""
        prediction = self.get_required(
            prediction_id
        )

        prediction.mark_expired()

        self.flush()

        return prediction

    def mark_superseded(
        self,
        *,
        prediction_id: uuid.UUID,
    ) -> Prediction:
        """Mark a prediction superseded by newer model output."""
        prediction = self.get_required(
            prediction_id
        )

        prediction.mark_superseded()

        self.flush()

        return prediction

    def invalidate(
        self,
        *,
        prediction_id: uuid.UUID,
        notes: str | None = None,
    ) -> Prediction:
        """Invalidate model output."""
        prediction = self.get_required(
            prediction_id
        )

        prediction.invalidate(
            notes=notes
        )

        self.flush()

        return prediction

    # ------------------------------------------------------------------
    # Outcome evaluation
    # ------------------------------------------------------------------

    def verify(
        self,
        *,
        prediction_id: uuid.UUID,
        outcome: PredictionOutcome,
        evaluated_at: datetime,
        actual_value: float | None = None,
        notes: str | None = None,
    ) -> Prediction:
        """
        Record the real outcome of a prediction.

        This information can later feed model evaluation and retraining
        pipelines.
        """
        prediction = self.get_required(
            prediction_id
        )

        prediction.verify(
            outcome=outcome,
            evaluated_at=evaluated_at,
            actual_value=actual_value,
            notes=notes,
        )

        self.flush()

        return prediction

    # ------------------------------------------------------------------
    # Model confidence
    # ------------------------------------------------------------------

